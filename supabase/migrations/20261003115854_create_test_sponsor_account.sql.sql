-- RETIRED 2026-10-15 — security remediation of audit finding R-03 (P0).
--
-- This migration used to provision two reusable test identities with
-- hardcoded passwords, and it ran against production.
--
-- It is deliberately emptied rather than deleted. Version 20261003115854 is
-- already recorded in the live database's migration history, so removing the
-- file would leave a recorded version with no counterpart in source and make
-- every future `supabase db push` report a divergence. An empty file keeps
-- the history consistent in both directions, changes nothing on the database
-- that already applied it, and guarantees that a fresh environment creates no
-- test accounts.
--
-- What it used to do, and why each part does not belong in a migration:
--
--   * INSERT/UPDATE auth.users with crypt('<literal>') for two accounts.
--     Published credentials for the live database — and because the UPDATE
--     branch reset the password on every run, rotating it in the dashboard
--     would not have held.
--   * INSERT/UPDATE public.user_accounts directly, which set the organizer
--     account to 'active' and bypassed the pending_approval state that
--     handle_new_user() assigns to every real organizer signup.
--   * ALTER TABLE ... DISABLE TRIGGER on event_partnerships and
--     event_partnership_obligations around the seed inserts, switching off the
--     rules that force created_by / completed_by to auth.uid() and that
--     forbid linking a sponsor organization outside the acceptance flow.
--   * DELETE FROM event_partnership_obligations for the seeded partnership on
--     every run.
--   * Seeded an organizer organization, a sponsor organization, an event, a
--     partnership, a role and three obligations so the Sponsor dashboard had
--     something to render.
--
-- The rule this establishes: a production migration defines schema and
-- controlled data changes. It never provisions a reusable login, never writes
-- an account past its approval state, and never disables a security trigger.
--
-- Demo data belongs in a separate, non-production Supabase project, seeded by
-- an explicitly invoked script that reads its credentials from the
-- environment and is never committed with them.
--
-- NOTE: emptying this file does not remove the credentials from git history.
-- They remain readable in earlier commits and must be treated as compromised
-- regardless of what this file now contains.
--
-- The rows this migration created in production are NOT removed here.
-- Deleting live accounts and their dependent data is a separate, explicitly
-- approved action; a migration that deleted accounts on the next deploy would
-- be its own hazard.
